"""Model comparison: open-source vs frontier LLM judges (and the local scorer), zero-shot, same anonymised payload.

Reads data/llm/<tag>/*.json written by eval.llm_eval and scores every report on the six quality metrics
(eval/quality.py) plus latency; repeats (*.rN.json) give consistency. Writes docs/EVAL_MODELS.md and
eval/results/models.json.

usage: python -m eval.compare tag1 tag2 ...   (tags = dirs under data/llm; 'local' scores the local scorer)"""
from __future__ import annotations

import glob
import json
import os
import sys
from collections import defaultdict

from rater.judge import judge
from rater.models import Analysis

from . import quality

HERE = os.path.dirname(__file__)
CACHE = os.path.join(HERE, "../data/cache")
LLM = os.path.join(HERE, "../data/llm")
OUT_MD = os.path.join(HERE, "../../docs/EVAL_MODELS.md")
FAMILY = {"open-source": ("qwen", "llama", "deepseek", "mistral", "gemma"), "frontier": ("gpt", "gemini", "claude", "o3", "o4")}


def family(tag: str) -> str:
    t = tag.lower()
    return next((f for f, keys in FAMILY.items() if any(k in t for k in keys)), "local")


def analyses() -> dict[str, tuple[dict, Analysis]]:
    out = {}
    for p in glob.glob(os.path.join(CACHE, "*.json")):
        if p.endswith(".asr.json"):
            continue
        with open(p) as fh:
            d = json.load(fh)
        out[d["id"]] = (d, Analysis(**d["analysis"]))
    return out


def evaluate(tag: str, an: dict, gold: dict) -> dict:
    runs: dict[str, list[dict]] = defaultdict(list)
    secs = []
    if tag == "local":
        for cid, (_, a) in an.items():
            runs[cid].append(judge(a, provider="local").model_dump())
    else:
        for p in sorted(glob.glob(os.path.join(LLM, tag, "*.json"))):
            with open(p) as fh:
                d = json.load(fh)
            runs[d["id"]].append(d["report"])
            secs.append(d.get("seconds", 0))
    rows, fallbacks = [], 0
    for cid, reps in runs.items():
        if cid not in an:
            continue
        r = reps[0]
        fallbacks += r.get("judge") == "local" and tag != "local"
        g = gold.get(quality.gold_key(cid))
        ev = {k: [q.model_dump() for q in v] for k, v in an[cid][1].evidence.items()}
        rows.append(quality.score_report(r, g, ev))
    cons = [quality.consistency(v) for v in runs.values() if len(v) > 1]
    agg = quality.aggregate(rows)
    agg.update(n=len(rows), family=family(tag), fallbacks_to_local=fallbacks,
               mean_seconds=round(sum(secs) / len(secs)) if secs else None,
               consistency_label_agree=round(sum(c["label_agree"] for c in cons) / len(cons), 2) if cons else None)
    return agg


def main():
    tags = sys.argv[1:] or sorted(os.listdir(LLM)) + ["local"]
    gold = quality.load_gold()
    an = analyses()
    res = {t: evaluate(t, an, gold) for t in tags}
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, "results/models.json"), "w") as fh:
        json.dump(res, fh, indent=1)
    cols = ["family", "n", "label_exact", "label_within1", "reasons_mapped", "evidence_exists", "evidence_supports",
            "specificity", "coverage_points", "consistency_label_agree", "fallbacks_to_local", "mean_seconds"]
    L = ["# Model comparison (zero-shot, same anonymised payload)", "",
         "Generated by `python -m eval.compare`. Label metrics are on the 10 labelled classes; nothing is fitted, so there is no test-fold leakage.",
         "Open-source models are for development; final numbers use frontier models via OpenRouter.", "",
         "| model | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for t, v in res.items():
        L.append(f"| {t} | " + " | ".join("" if v.get(c) is None else (f"{v[c]:.0%}" if isinstance(v[c], float) and c not in ("mean_seconds",) else str(v[c])) for c in cols) + " |")
    with open(OUT_MD, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
